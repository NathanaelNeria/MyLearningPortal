// Metadata kolom untuk ditampilkan di schema browser.
export function tableNames() {
  return TABLES.map((t) => t.name);
}

export function getTable(name) {
  return TABLES.find((t) => t.name === name);
}

function sqlLiteral(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

export function buildSchemaSQL() {
  const parts = [];
  for (const t of TABLES) {
    const colDefs = t.columns
      .map(([name, type]) => `${name} ${name === 'id' ? 'INTEGER PRIMARY KEY' : type}`)
      .join(', ');
    parts.push(`CREATE TABLE ${t.name} (${colDefs});`);
    const colNames = t.columns.map(([name]) => name).join(', ');
    for (const row of t.rows) {
      parts.push(`INSERT INTO ${t.name} (${colNames}) VALUES (${row.map(sqlLiteral).join(', ')});`);
    }
  }
  return parts.join('\n');
}
